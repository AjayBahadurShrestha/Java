class BitwiseOP{
	public static void main(String...args){

	System.out.println(5&6);
	System.out.println(5|6);
	System.out.println(5^6);
	System.out.println(10<<3);
	System.out.println(-10<<2);
	System.out.println(52>>2);
	System.out.println(-48>>2);
	System.out.println(52>>>3);
	System.out.println(-52>>>3);
	System.out.println(~10);
	System.out.println(~-10);
	

	
	
	}
	
}
	
	